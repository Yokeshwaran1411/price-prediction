import { useNavigate } from 'react-router-dom';
import { Search, BarChart2, Brain, FileText, AlertTriangle, Rocket } from 'lucide-react';
import { useInView } from '../hooks/useInView';
import './HowItWorksPage.css';

const STEPS = [
  { num: '01', Icon: Search,    title: 'Search & Select a Stock', desc: 'Browse 6,200+ Indian equities listed on NSE and BSE. Use the smart search to find any stock by symbol or company name.' },
  { num: '02', Icon: BarChart2, title: 'View Live Metrics',       desc: 'Instantly see the stock\'s price trend chart, volume, P/E ratio, 52-week range, and daily high/low data.' },
  { num: '03', Icon: Brain,     title: 'Activate StockGPT AI',   desc: 'Click "Generate AI Prediction" and our backend sends the stock context to the AI predictive model for deep synthesis.' },
  { num: '04', Icon: FileText,  title: 'Read the Report',         desc: 'Receive a structured prediction report with sentiment rating, short-term price direction, risk factors, and key signals.' },
];

function StepCard({ step, index }) {
  const [ref, inView] = useInView();
  return (
    <div
      ref={ref}
      className={`step-card${inView ? ' is-visible' : ''}`}
      style={{ transitionDelay: `${index * 0.1}s` }}
    >
      <div className="step-num-badge">{step.num}</div>
      <div className="step-icon">
        <step.Icon size={32} strokeWidth={1.6} />
      </div>
      <h3 className="step-title">{step.title}</h3>
      <p className="step-desc">{step.desc}</p>
      {index < STEPS.length - 1 && <div className="step-connector">→</div>}
    </div>
  );
}

export default function HowItWorksPage() {
  const navigate = useNavigate();
  const [disclaimerRef, disclaimerInView] = useInView();
  const [ctaRef, ctaInView] = useInView();

  return (
    <div className="hiw-page">
      {/* Header */}
      <section className="hiw-header">
        <div className="container">
          <div className="section-label">Under the Hood</div>
          <h1 className="hiw-title">How StockGPT Works</h1>
          <p className="hiw-sub">
            From raw stock data to AI-powered predictions — here's the full picture of how our platform works in under 5 seconds.
          </p>
        </div>
      </section>

      {/* Steps */}
      <section className="hiw-steps-section">
        <div className="container">
          <div className="steps-grid">
            {STEPS.map((s, i) => (
              <StepCard key={s.num} step={s} index={i} />
            ))}
          </div>
        </div>
      </section>

      {/* Disclaimer */}
      <section className="hiw-disclaimer">
        <div className="container">
          <div
            ref={disclaimerRef}
            className={`disclaimer-card${disclaimerInView ? ' is-visible' : ''}`}
          >
            <span className="disclaimer-icon">
              <AlertTriangle size={24} strokeWidth={1.8} />
            </span>
            <div>
              <h4>Important Disclaimer</h4>
              <p>
                All predictions and analysis generated by StockGPT are powered by a generative AI model and are intended for educational and informational purposes only. They do not constitute financial advice. Always consult a certified financial advisor before making investment decisions. Past performance of AI-generated signals does not guarantee future results.
              </p>
            </div>
          </div>
        </div>
      </section>

      {/* CTA */}
      <section ref={ctaRef} className={`hiw-cta${ctaInView ? ' is-visible' : ''}`}>
        <div className="container">
          <h2>Start your first analysis</h2>
          <p>It takes less than 5 seconds to get a full AI prediction report for any Indian stock.</p>
          <button className="btn btn-primary btn-lg" onClick={() => navigate('/stocks')}>
            <Rocket size={16} strokeWidth={2} />
            Go to Markets
          </button>
        </div>
      </section>
    </div>
  );
}
